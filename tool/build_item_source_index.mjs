// Build-time presentation index only. No network, profiles, or runtime I/O.
// Emit generated source on stdout; --audit emits the underlying factual records.
import fs from 'node:fs';
import crypto from 'node:crypto';
const source = fs.readFileSync('packages/bdo_map_core/assets/data/resource_map.json');
const map = JSON.parse(source);
const catalog = JSON.parse(fs.readFileSync('assets/data/app-data.json'));
const recipes = [catalog.items, catalog.cooking.items, catalog.processing.items];
const reachable = new Set(Object.values(catalog.acquisitionInfo).map(r=>r.itemId).filter(Number.isInteger));
for (const group of recipes) for(const recipe of Object.values(group)) if(recipe.marketId) reachable.add(Number(recipe.marketId));
const excludedRegionalNodes = new Set(['1826','1827','1828','1829']);
const labels = {Excavation:'Excavation nodes',Mining:'Mining nodes',Farm:'Farm nodes',Forest:'Timber nodes',Lumbering:'Timber nodes',Gathering:'Gathering nodes',Mushrooms:'Mushroom nodes','Fish Drying Yard':'Fishing nodes',Fishing:'Fishing nodes'};
const grains = new Set(['Wheat','Barley','Potato','Corn','Sweet Potato','Rice','Teff','Freekeh']);
const records = [];
for(const resource of map.resources) {
  if(!Number.isInteger(resource.gameItemId)||!reachable.has(resource.gameItemId))continue;
  const nodes=map.workerNodes.filter(n=>n.isResourceNode && n.isProductionNode && !excludedRegionalNodes.has(n.id) && n.outputs.some(o=>o.gameItemId===resource.gameItemId && o.resourceId===resource.id));
  const activities = new Set();
  for(const node of nodes) {
    let type=node.nodeType;
    if(type==='Mine')type=node.name.split(' - ').at(-1);
    let label=labels[type];
    if(!label)throw Error(`Unreviewed production category ${node.id}: ${type}`);
    if(type==='Farm'&&grains.has(resource.name))label='Grain nodes';
    if(type==='Farm'&&node.name.endsWith(' - Chicken Meat Production'))label='Chicken farms';
    if(type==='Gathering'&&resource.category==='Mushrooms')label='Mushroom nodes';
    if(type==='Gathering'&&resource.category==='Plants & flowers')label='Plant nodes';
    activities.add(label);
  }
  // Field instructions carry their tool and target. Do not infer additional
  // methods from resource names, generic categories, icons or old coordinates.
  const fields = map.fieldSources.flatMap(f=>f.products.filter(p=>p.resourceId===resource.id && p.instruction?.trim()).map(p=>({sourceId:f.id,name:f.name,method:p.method,tool:p.tool,instruction:p.instruction})));
  if(!nodes.length&&!fields.length)continue;
  records.push({id:resource.gameItemId,name:resource.name,worker:[...activities].sort().map(s=>`Workers · ${s}`),fields,nodeIds:nodes.map(n=>n.id)});
}
records.sort((a,b)=>a.id-b.id);
const sha256=crypto.createHash('sha256').update(source).digest('hex');
if(process.argv.includes('--audit'))console.log(JSON.stringify({dataset:map.manifest.datasetVersion,sha256,excludedRegionalNodes:[...excludedRegionalNodes],records},null,2));
else {
  const quote=s=>JSON.stringify(s).replaceAll('$','\\$');
  const list=a=>`[${a.map(quote).join(', ')}]`;
  console.log(`// Generated by tool/build_item_source_index.mjs; presentation facts only.\n// Map snapshot: ${map.manifest.datasetVersion}; SHA-256: ${sha256}.\n// Do not edit by hand. No market eligibility or grade inference.\nconst bundledItemSourceMapSha256 = '${sha256}';\nconst bundledItemSourceHints = <int, ({String name, List<String> workers, List<String> gathering})>{`);
  for(const r of records)console.log(`  ${r.id}: (name: ${quote(r.name)}, workers: ${list(r.worker)}, gathering: ${list([...new Set(r.fields.map(f=>f.instruction))])}),`);
  console.log('};');
}
