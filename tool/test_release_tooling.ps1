[CmdletBinding()]
param(
    [string]$PowerShellPath = (Get-Process -Id $PID).Path,
    [string]$PythonPath
)
Set-StrictMode -Version Latest
$ErrorActionPreference = 'Stop'
$project = [IO.Path]::GetFullPath((Join-Path $PSScriptRoot '..'))
. (Join-Path $PSScriptRoot 'release/verified_input_cache.ps1')
. (Join-Path $PSScriptRoot 'release/preflight.ps1')
. (Join-Path $PSScriptRoot 'release/stage_metrics.ps1')
. (Join-Path $PSScriptRoot 'release/source_inventory.ps1')
$null = Assert-ReleasePreflightFile -Path $PowerShellPath -Label 'PowerShell test runtime'
$testNames = @(
    'release_input_cache_test.ps1',
    'release_source_inventory_test.ps1',
    'release_preflight_metrics_test.ps1',
    'release_builder_integration_test.ps1',
    'release_payload_scan_test.ps1',
    'publish_verified_release_test.ps1',
    'release_source_promotion_test.ps1',
    'release_plan_lifecycle_test.ps1',
    'release_git_privacy_scan_test.ps1',
    'release_build_checkpoint_test.ps1',
    'release_metrics_durability_test.ps1',
    'release_dependency_native_test.ps1',
    'release_streaming_scan_test.ps1',
    'release_workflow_test.ps1',
    'release_installed_payload_test.ps1',
    'release_checkpoint_builder_test.ps1'
)
$runId = 'self-tests-' + [Guid]::NewGuid().ToString('N')
$output = Join-Path $project "build/release-tooling-tests/$runId"
$null = Assert-ReleaseOrdinaryPath -Path $output
$null = [IO.Directory]::CreateDirectory($output)
$metrics = New-ReleaseStageMetrics -RunId $runId
$manifest = [Collections.Generic.List[object]]::new()
$toolingInputPaths = [Collections.Generic.List[string]]::new()
$initialReleasePaths = (Get-ReleaseSourceInventory -RootPath (Join-Path $PSScriptRoot 'release') -ExcludedPathPattern '').FilePaths
foreach ($relative in $initialReleasePaths) {
    if ($relative -match '(?:^|/)__pycache__/|\.pyc$') { throw 'Remove generated bytecode from the tooling input set before validation.' }
    $toolingInputPaths.Add('tool/release/' + $relative)
}
foreach ($relative in @('tool/test_release_tooling.ps1', 'tool/build_stable_release_candidate.ps1',
    'tool/build_public_stable_candidate.ps1', 'tool/verify_production_source.ps1',
    'test/tool/test_git_object_privacy.py', 'test/tool/test_installed_payload.py')) { $toolingInputPaths.Add($relative) }
foreach ($testName in $testNames) { $toolingInputPaths.Add('test/tool/' + $testName) }
$toolingInputPaths.Sort([StringComparer]::Ordinal)
$toolingInputs = @($toolingInputPaths | ForEach-Object {
    [ordered]@{ file = $_; sha256 = (Get-FileHash -LiteralPath (Join-Path $project $_) -Algorithm SHA256).Hash }
})
$savedPythonPath = $env:BSL_RELEASE_PYTHON
$toolingInputsStable = $false
$allTestsPassed = $false
if (-not [string]::IsNullOrWhiteSpace($PythonPath)) {
    $pythonRuntime = Assert-ReleasePreflightFile -Path $PythonPath -Label 'Python test runtime'
    $env:BSL_RELEASE_PYTHON = $pythonRuntime.FullName
}
$selectedPythonSha256 = $null
if (-not [string]::IsNullOrWhiteSpace($env:BSL_RELEASE_PYTHON) -and
    (Test-Path -LiteralPath $env:BSL_RELEASE_PYTHON -PathType Leaf)) {
    $selectedPythonSha256 = (Get-FileHash -LiteralPath $env:BSL_RELEASE_PYTHON -Algorithm SHA256).Hash
}
try {
    foreach ($testName in $testNames) {
        $testPath = Join-Path $project "test/tool/$testName"
        $stage = Start-ReleaseStage -Metrics $metrics -Name ([IO.Path]::GetFileNameWithoutExtension($testName))
        try {
            $null = Assert-ReleasePreflightFile -Path $testPath -Label $testName
            $parseErrors = $null
            $null = [Management.Automation.Language.Parser]::ParseFile($testPath, [ref]$null, [ref]$parseErrors)
            if ($parseErrors.Count -ne 0) { throw "Test syntax failed: $testName" }
            $manifest.Add([ordered]@{
                file = "test/tool/$testName"
                sha256 = (Get-FileHash -LiteralPath $testPath -Algorithm SHA256).Hash
            })
            # Only this child process gets the local-script execution setting;
            # no machine/user policy or other Windows setting is modified.
            $PSNativeCommandUseErrorActionPreference = $false
            $global:LASTEXITCODE = $null
            $savedPreference = $ErrorActionPreference
            try {
                $ErrorActionPreference = 'Continue'
                $lines = @(& $PowerShellPath -NoProfile -NonInteractive -ExecutionPolicy Bypass -File $testPath 2>&1)
                $testExitCode = $global:LASTEXITCODE
            }
            finally { $ErrorActionPreference = $savedPreference }
            $text = ($lines | ForEach-Object { [string]$_ }) -join "`r`n"
            [IO.File]::WriteAllText((Join-Path $output "$testName.log"), $text, [Text.UTF8Encoding]::new($false))
            Write-Host $text
            Assert-ReleaseCommandExit -Operation $testName -ExitCode $testExitCode
            Complete-ReleaseStage -Metrics $metrics -Stage $stage -Outcome Passed -CacheState NotApplicable
        }
        catch {
            Complete-ReleaseStage -Metrics $metrics -Stage $stage -Outcome Failed -FailureCode 'tooling-test-failed'
            throw
        }
        finally { Save-ReleaseStageMetrics -Metrics $metrics -Path (Join-Path $output 'stage-metrics.json') }
    }
    foreach ($inputRecord in $toolingInputs) {
        if ((Get-FileHash -LiteralPath (Join-Path $project $inputRecord.file) -Algorithm SHA256).Hash -cne $inputRecord.sha256) {
            throw 'Tooling inputs changed during tests; these results cannot be adopted as a stable baseline.'
        }
    }
    $finalReleasePaths = (Get-ReleaseSourceInventory -RootPath (Join-Path $PSScriptRoot 'release') -ExcludedPathPattern '').FilePaths
    if (($initialReleasePaths -join '|') -cne ($finalReleasePaths -join '|')) {
        throw 'Tooling files were added or removed during tests; baseline is not stable.'
    }
    $toolingInputsStable = $true
    $allTestsPassed = $true
}
finally {
    $env:BSL_RELEASE_PYTHON = $savedPythonPath
    $document = [ordered]@{
        schemaVersion = 1; purpose = 'release-tooling-self-tests'
        isApplicationAcceptance = $false; isReleaseVerification = $false
        isAutomaticResumeReceipt = $false
        allTestsPassed = $allTestsPassed
        toolingInputsStable = $toolingInputsStable
        runnerPowerShell = $PSVersionTable.PSVersion.ToString()
        childPowerShellExecutableSha256 = (Get-FileHash -LiteralPath $PowerShellPath -Algorithm SHA256).Hash
        selectedPythonExecutableSha256 = $selectedPythonSha256
        operatingSystem = [Environment]::OSVersion.VersionString
        toolingInputs = $toolingInputs
        tests = @($manifest.ToArray())
    }
    [IO.File]::WriteAllText((Join-Path $output 'test-manifest.json'),
        ($document | ConvertTo-Json -Depth 5), [Text.UTF8Encoding]::new($false))
    Write-Host "Tooling test evidence: $output"
}
