// Emits only the reviewed November delta. It cannot relabel historical formulas.
// Redirect stdout to a review artifact; apply the inspected result separately.
import 'dart:convert';
import 'dart:io';

import 'package:bdo_craft_planner_flutter/app/planning/planner_assembly.dart';
import 'package:bdo_craft_planner_flutter/data/catalog/bundled_catalog_parser.dart';
import 'package:bdo_craft_planner_flutter/domain/models/catalog_models.dart';
import 'package:bdo_craft_planner_flutter/domain/models/craft_mode.dart';
import 'package:bdo_craft_planner_flutter/domain/opportunities/recipe_experience.dart';
import 'package:bdo_craft_planner_flutter/domain/state/planner_state.dart';

const _reviewedSha =
    '849e731897556a56bfead1cc06102d2a08e69e17f53f1a30a798ab787599c8e6';

void main() {
  if (productionCatalogSha256 != _reviewedSha) {
    throw StateError('Review changed formulas before regenerating this delta.');
  }
  final catalog = const BundledCatalogParser().parse(
    File('assets/data/app-data.json').readAsStringSync(),
  );
  const rows = <(CraftMode, String, double, String)>[
    (
      CraftMode.alchemy,
      'Defense Elixir',
      460,
      'https://bdocodex.com/us/recipe/27/',
    ),
    (
      CraftMode.alchemy,
      'Elixir of Perforation',
      1610,
      'https://bdocodex.com/us/recipe/9/',
    ),
    (
      CraftMode.alchemy,
      'Looney Elixir',
      920,
      'https://bdocodex.com/us/recipe/218/',
    ),
    (
      CraftMode.cooking,
      'Soft Bread',
      400,
      'https://bdocodex.com/us/recipe/129/',
    ),
    (CraftMode.processing, 'Pure Copper Crystal', 1000, '4059:9ce5a816562b'),
    (CraftMode.processing, 'Pure Gold Crystal', 1500, '4256:c1484d38c2b1'),
    (CraftMode.processing, 'Pure Iron Crystal', 1000, '4053:eefdc45594da'),
    (CraftMode.processing, 'Pure Lead Crystal', 1000, '4056:f6d854bbf62f'),
    (CraftMode.processing, 'Pure Platinum Crystal', 1500, '4259:a9b56e0748ce'),
    (CraftMode.processing, 'Pure Silver Crystal', 1500, '4253:fe1386681ef4'),
    (CraftMode.processing, 'Pure Tin Crystal', 1000, '4062:3c5988fe25f6'),
    (CraftMode.processing, 'Pure Titanium Crystal', 1000, '4083:0af8acf50ac2'),
    (CraftMode.processing, 'Pure Vanadium Crystal', 1000, '4080:d36e70804a1b'),
    (CraftMode.processing, 'Pure Zinc Crystal', 1000, '4065:7bfc3503df2b'),
  ];
  final entries = <String, RecipeExperience>{};
  for (final mode in CraftMode.values) {
    final assembled = const PlannerAssembly().assembleRecipes(
      catalog: catalog.forMode(mode),
      state: ModeState(
        target: '',
        bonusTarget: '',
        market: MarketState(),
        appearance: AppearanceSettings.defaultsFor(mode),
      ),
      supportingData: catalog.supportingData,
      sharedMetadata: catalog.alchemy.metadata,
      mode: mode,
      processingRecipes: catalog.processing.items,
    );
    for (final row in rows.where((row) => row.$1 == mode)) {
      for (final recipes in <Map<String, Recipe>>[
        catalog.forMode(mode).items,
        assembled,
      ]) {
        final recipe = recipes[row.$2]!;
        final source = row.$4.startsWith('https://')
            ? row.$4
            : 'https://bdolytics.com/api/trpc/calculator.getCraftingRecipes recipes=${row.$4}';
        entries['${mode.key}|${row.$2.toLowerCase()}|${recipeExperienceSignature(recipe)}'] =
            RecipeExperience(
              value: row.$3,
              estimated: false,
              skill: experienceSkillFor(recipe)!,
              sourceReference: '$source reviewed=2026-11-02',
            );
      }
    }
  }
  final out = StringBuffer()
    ..writeln('// GENERATED by tool/generate_reviewed_recipe_experience.dart.')
    ..writeln('// Reviewed 2026-11-02; catalog SHA-256: $_reviewedSha')
    ..writeln(
      '// Exact positive secondary-reference matches; not a new server EXP certification.',
    )
    ..writeln("part of 'recipe_experience.dart';")
    ..writeln(
      'const _reviewedRecipeExperienceReferences = <String, RecipeExperience>{',
    );
  for (final key in entries.keys.toList()..sort()) {
    final e = entries[key]!;
    out
      ..writeln('  ${jsonEncode(key)}: RecipeExperience(')
      ..writeln(
        '    value: ${e.value}, estimated: false, skill: ${jsonEncode(e.skill)},',
      )
      ..writeln('    sourceReference: ${jsonEncode(e.sourceReference)},')
      ..writeln('  ),');
  }
  out.writeln('};');
  stdout.write(out);
}
