# A package_config has no lockfile fingerprint. This receipt is created only by
# the explicit preparation command after a successful lock-enforced resolution.
# It is local evidence, not permission to skip application tests or a build key.
function Get-ReleaseDependencyFilePin([string]$Path, [string]$Role) {
    $full = [IO.Path]::GetFullPath($Path)
    $current = $full
    while (-not [string]::IsNullOrWhiteSpace($current)) {
        if (Test-Path -LiteralPath $current) {
            $entry = Get-Item -LiteralPath $current -Force -ErrorAction Stop
            if (($entry.Attributes -band [IO.FileAttributes]::ReparsePoint) -ne 0) {
                throw "Prepared dependencies reject a reparse path: $Role."
            }
        }
        $current = Split-Path -Parent $current
    }
    $item = Get-Item -LiteralPath $full -Force -ErrorAction Stop
    if ($item.PSIsContainer -or $item.Length -eq 0) { throw "Prepared dependencies require a non-empty file: $Role." }
    return [ordered]@{ role = $Role; bytes = $item.Length; sha256 = (Get-FileHash -LiteralPath $full -Algorithm SHA256).Hash }
}

function Get-ReleaseDependencySnapshot([string]$PackageRoot, [string]$FlutterPath) {
    $root = [IO.Path]::GetFullPath($PackageRoot).TrimEnd('\', '/')
    $pins = [Collections.Generic.List[object]]::new()
    foreach ($name in @('pubspec.yaml', 'pubspec.lock', 'pubspec_overrides.yaml')) {
        $path = Join-Path $root $name
        if ($name -ceq 'pubspec_overrides.yaml' -and -not (Test-Path -LiteralPath $path)) { continue }
        $pins.Add((Get-ReleaseDependencyFilePin $path $name))
    }
    $configPath = Join-Path $root '.dart_tool\package_config.json'
    $pins.Add((Get-ReleaseDependencyFilePin $configPath 'package-config'))
    try { $config = Get-Content -LiteralPath $configPath -Raw | ConvertFrom-Json -ErrorAction Stop }
    catch { throw 'Prepared dependencies require a valid package_config.json.' }
    if (($config.configVersion -isnot [int] -and $config.configVersion -isnot [long]) -or $config.configVersion -ne 2 -or
        $config.packages -isnot [Array] -or $config.packages.Count -eq 0 -or
        $config.generator -cne 'pub') {
        throw 'Prepared dependencies require a populated version-2 pub package configuration.'
    }
    $flutterBin = Split-Path -Parent ([IO.Path]::GetFullPath($FlutterPath))
    $metadataPath = Join-Path $flutterBin 'cache\flutter.version.json'
    $metadata = Get-Content -LiteralPath $metadataPath -Raw | ConvertFrom-Json
    $dartVersion = [regex]::Match([string]$metadata.dartSdkVersion, '^[0-9]+\.[0-9]+\.[0-9]+').Value
    if ([string]::IsNullOrWhiteSpace($dartVersion) -or [string]$config.generatorVersion -cne $dartVersion) {
        throw 'Prepared dependency configuration was generated by a different Dart SDK.'
    }
    foreach ($record in @(
        @('flutter-launcher', $FlutterPath), @('flutter-version', $metadataPath),
        @('dart-runtime', (Join-Path $flutterBin 'cache\dart-sdk\bin\dart.exe')),
        @('flutter-tools', (Join-Path $flutterBin 'cache\flutter_tools.snapshot'))
    )) { $pins.Add((Get-ReleaseDependencyFilePin $record[1] $record[0])) }
    $names = [Collections.Generic.HashSet[string]]::new([StringComparer]::OrdinalIgnoreCase)
    $configUri = [Uri]::new($configPath)
    $rootMatches = 0
    foreach ($package in @($config.packages | Sort-Object -Property name)) {
        if ($package.name -isnot [string] -or $package.name -cnotmatch '^[a-z][a-z0-9_]*$' -or
            -not $names.Add([string]$package.name)) { throw 'Prepared dependency package names are invalid or duplicated.' }
        $uri = [Uri]::new($configUri, [string]$package.rootUri)
        if (-not $uri.IsFile -or $uri.IsUnc -or $uri.Query -or $uri.Fragment) { throw 'Prepared dependency root must resolve to a local file URI.' }
        $packageDirectory = [IO.Path]::GetFullPath($uri.LocalPath).TrimEnd('\', '/')
        if ($packageDirectory.Equals($root, [StringComparison]::OrdinalIgnoreCase)) { $rootMatches++ }
        $pins.Add((Get-ReleaseDependencyFilePin (Join-Path $packageDirectory 'pubspec.yaml') ("package/$($package.name)/pubspec")))
        if ($package.packageUri -isnot [string] -or $package.packageUri -cne 'lib/') {
            throw 'Prepared dependency packageUri must use the reviewed lib/ contract.'
        }
        if (-not (Test-Path -LiteralPath (Join-Path $packageDirectory 'lib') -PathType Container)) {
            throw 'Prepared dependency library directory is missing.'
        }
    }
    if ($rootMatches -ne 1) { throw 'Prepared dependency configuration does not identify this package root exactly once.' }
    return [ordered]@{ schemaVersion = 1; files = @($pins.ToArray()) }
}

function Assert-ReleasePreparedDependencies {
    [CmdletBinding()]
    param(
        [Parameter(Mandatory = $true)][string]$PackageRoot,
        [Parameter(Mandatory = $true)][string]$FlutterPath,
        [Parameter(Mandatory = $true)][string]$ReceiptPath,
        [Parameter(Mandatory = $true)][string]$ApprovedReceiptSha256
    )
    $pin = Get-ReleaseDependencyFilePin $ReceiptPath 'dependency receipt'
    if ($ApprovedReceiptSha256 -notmatch '^[0-9A-Fa-f]{64}$' -or $pin.sha256 -cne $ApprovedReceiptSha256.ToUpperInvariant()) {
        throw 'Prepared dependency receipt SHA-256 does not match the approved value.'
    }
    $receipt = Get-Content -LiteralPath $ReceiptPath -Raw | ConvertFrom-Json
    if (($receipt.schemaVersion -isnot [int] -and $receipt.schemaVersion -isnot [long]) -or $receipt.schemaVersion -ne 1 -or
        $receipt.resolutionSucceeded -isnot [bool] -or -not $receipt.resolutionSucceeded -or
        $receipt.command -cne 'flutter pub get --enforce-lockfile') {
        throw 'Prepared dependency receipt does not record successful lock-enforced preparation.'
    }
    $actual = Get-ReleaseDependencySnapshot $PackageRoot $FlutterPath
    if (($actual | ConvertTo-Json -Depth 8 -Compress) -cne ($receipt.snapshot | ConvertTo-Json -Depth 8 -Compress)) {
        throw 'Prepared dependency receipt is stale: package, lock, configuration, dependency pubspec or SDK changed. Prepare dependencies separately.'
    }
    return [ordered]@{ receiptSha256 = $pin.sha256; packageCount = @($actual.files | Where-Object { $_.role.StartsWith('package/') }).Count; noPubPrerequisite = 'lock-enforced-receipt-revalidated'; isBuildCacheKey = $false }
}
