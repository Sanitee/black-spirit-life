/// Apply to the reviewed historical seed, or accept an already-corrected seed.
/// Fail closed if identities/costs have changed; never overwrite an unknown update.
List<Map<String, Object?>> applyNovemberReviewedNodeCosts(
  List<Map<String, Object?>> nodes,
) {
  for (final entry in novemberReviewedNodeCosts.entries) {
    final matches = nodes.where((node) => node['id'] == entry.key).toList();
    if (matches.length != 1 ||
        matches.single['name'] != entry.value.name ||
        !{
          entry.value.before,
          entry.value.after,
        }.contains(matches.single['contributionPoints'])) {
      throw FormatException('Re-review node cost and identity: ${entry.key}.');
    }
  }
  return [
    for (final node in nodes)
      if (novemberReviewedNodeCosts[node['id']] case final correction?)
        {...node, 'contributionPoints': correction.after}
      else
        {...node},
  ];
}
