  id: id,
  inputCount: input,
  rewards: [
    const ExchangeReward.utility('Contribution EXP', quantity: 900),
    ExchangeReward.utility('$skill EXP', quantity: 30),
  ],
  location: location,
  notes: const ['Experience is useful, but is not silver income.'],
);

ExchangeCurrency _currency({
  required String id,
  required int itemId,
  required String activity,
  required List<ExchangeRoute> routes,
  List<String> notes = const [],
  List<ExchangeSource> sources = const [],
  bool legacy = false,
}) {
  final item = exchangeItems[itemId]!;
  return ExchangeCurrency(
    id: id,
    item: item,
    sourceActivity: activity,
    legacy: legacy,
    routes: List.unmodifiable([
      ...routes,
      if (item.vendorSellPrice != null)
        ExchangeRoute(
          id: '$id-vendor',
          inputCount: 1,
          rewards: [ExchangeReward.item(item)],
          location: 'NPC shop',
          directVendorSale: true,
          notes: const ['Sell the currency itself. No Marketplace tax.'],
        ),
    ]),
    notes: notes,
    sources: List.unmodifiable([_itemSource(itemId), ...sources]),
  );
}

