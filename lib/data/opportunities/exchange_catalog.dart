ExchangeRoute _route(
  String id,
  int input,
  int outputId,
  int output,
  String location, {
  ExchangeLimit limit = const ExchangeLimit.repeatable(),
  List<String> requirements = const [],
  List<String> notes = const [],
  List<ExchangeSource> sources = const [],
  int? containerItemId,
}) => ExchangeRoute(
  id: id,
  inputCount: input,
  rewards: [ExchangeReward.item(exchangeItems[outputId]!, quantity: output)],
  location: location,
  limit: limit,
  requirements: requirements,
  notes: notes,
  sources: sources,
  rewardContainer: containerItemId == null
      ? null
      : exchangeItems[containerItemId],
);

ExchangeRoute _experience(
  String id,
  int input,
  String skill,
  String location,
